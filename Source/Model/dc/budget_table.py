"""The per-block triangle budget table in docs/triangle-budgets.md, generated from the committed export.json files.

    python3 Source/Model/dc/budget_table.py          rewrites the table between the two markers in the doc
    Tests/test_states_docs.py                         fails when the doc differs from budget_table.table()

Columns (LOD0 triangles): NF = the plain model, FR = the Fractured model (scaffold and stand-ins included),
limit = Keen's fractured limit for it (the manifest's budget[0]; for the four unfractured blocks se2model.limits),
scaffold / stand-ins = the part of FR LOD0 they take (the stand-ins exist in FR and DM only), DM = the Damaged
model and its limit (the one the build enforces: the fractured budget[0], Tests/test_damaged_geometry.py; for the
four unfractured blocks se2model.limits), LODs = the FR LOD count."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..", "..", "..", "..", "tools")))

from dc import catalog, config  # noqa: E402
from dc.assetio import read_json  # noqa: E402
from se2model import limits  # noqa: E402

BEGIN = "<!-- budget-table:begin (generated by Source/Model/dc/budget_table.py; do not edit) -->"
END = "<!-- budget-table:end -->"
HEADER = ("| Block | NF | FR LOD0 | FR limit | Scaffold | Stand-ins | DM LOD0 | DM limit | FR LODs |\n"
          "|---|---:|---:|---:|---:|---:|---:|---:|---:|")


def _limit(man):
    """LOD0 limit of the Fractured and the Damaged model: the fractured budget[0] the build enforces on both."""
    if man["fractured"].get("budget"):
        return man["fractured"]["budget"][0]
    size = tuple(man["fractured"].get("size") or man["nonfractured"]["size"])
    fr0 = man["fractured"]["lods"][0]["tris"]
    return limits.model_limits(size, fr0, fractured=True)["lods"][0]["max_tris"]


def row(name):
    man = read_json(os.path.join(config.MODELS_DIR, name, "export.json"))
    fr, dm = man["fractured"], man["damaged"]
    sc = ((fr.get("scaffold") or {}).get("tris") or {}).get("0", 0)
    si = ((fr.get("standins") or {}).get("tris") or {}).get("0", 0)
    return {"name": name, "nf": man["nonfractured"]["lods"][0]["tris"], "fr": fr["lods"][0]["tris"],
            "fr_limit": _limit(man), "scaffold": sc, "standins": si,
            "dm": dm["lods"][0]["tris"], "dm_limit": _limit(man), "lods": len(fr["lods"])}


def rows():
    return [row(b.name) for b in catalog.BLOCKS]


def _n(v):
    return f"{v:,}".replace(",", " ") if v else "-"


def table():
    out = [HEADER]
    for r in rows():
        out.append(f"| {r['name']} | {_n(r['nf'])} | {_n(r['fr'])} | {_n(r['fr_limit'])} | {_n(r['scaffold'])} | "
                   f"{_n(r['standins'])} | {_n(r['dm'])} | {_n(r['dm_limit'])} | {r['lods']} |")
    return "\n".join(out)


def block():
    return f"{BEGIN}\n{table()}\n{END}"


def doc_path():
    return os.path.join(config.MOD_DIR, "docs", "triangle-budgets.md")


def rewrite(path=None):
    path = path or doc_path()
    with open(path, encoding="utf-8") as f:
        text = f.read()
    a, b = text.index(BEGIN), text.index(END) + len(END)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text[:a] + block() + text[b:])


if __name__ == "__main__":
    rewrite()
